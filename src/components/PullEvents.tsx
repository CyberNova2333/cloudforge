import type { ReactNode } from 'react';
import { Link } from 'react-router-dom';
import {
  AlertIcon,
  CheckIcon,
  DotFillIcon,
  GitBranchIcon,
  LightBulbIcon,
  ShieldCheckIcon,
  TagIcon,
  XIcon,
} from '@primer/octicons-react';
import type { PullEvent, PullReason } from '@/lib/uiApi';
import { t, tx } from '@/lib/i18n';
import { blocking, reasonText, stateLabel } from '@/lib/pullState';
import { fullDate, timeAgo } from '@/lib/format';
import { learnedPhrase, learnedText } from '@/lib/lessons';
import { rebasedText } from '@/lib/rebaseStatus';
import { STATE_TONE } from '@/lib/pullPage';

const num = (v: unknown) => (typeof v === 'number' ? v : null);
const str = (v: unknown) => (typeof v === 'string' && v ? v : null);

/** One small row on the conversation's line: an icon in a circle, then the sentence. */
export function EventRow({
  icon,
  tone,
  children,
}: {
  icon: ReactNode;
  /** Fills the circle: `merged`, `closed`. */
  tone?: 'merged' | 'closed';
  children: ReactNode;
}) {
  return (
    <div className="pr-event">
      <span className={`pr-event-icon${tone ? ` ${tone}` : ''}`}>{icon}</span>
      <div className="pr-event-body">{children}</div>
    </div>
  );
}
const Row = EventRow;

/** One GitOrange timeline entry, a row on the conversation's line. `repoPath` is `/owner/name`. */
export function PullEventItem({
  e,
  repoPath,
}: {
  e: PullEvent;
  repoPath: string;
}) {
  const d = e.data ?? {};
  const pr = (n: number | null) =>
    n === null ? null : <Link to={`${repoPath}/pull/${n}`}>#{n}</Link>;
  const when = (
    <time
      className="muted"
      dateTime={e.createdAt}
      title={fullDate(e.createdAt)}
    >
      {' '}
      {timeAgo(e.createdAt)}
    </time>
  );
  if (e.kind === 'state_changed' && e.state) {
    const all = (d.reasons as PullReason[]) ?? [];
    const reasons = all.filter(blocking);
    return (
      <Row icon={<DotFillIcon />}>
        <span className={`chip ${STATE_TONE[e.state]}`}>
          {stateLabel({ state: e.state, reasons: all })}
        </span>{' '}
        {reasons.length > 0 && (
          <span>{reasons.map(reasonText).join('; ')}</span>
        )}
        {when}
      </Row>
    );
  }
  if (e.kind === 'stacked') {
    const branch = str(d.branch);
    return (
      <Row icon={<GitBranchIcon />}>
        {tx('Stacked on {pull}', { pull: pr(num(d.pr)) })}
        {branch && (
          <>
            {' '}
            (<code>{branch}</code>)
          </>
        )}
        {str(d.reason) && <>: {str(d.reason)}</>}
        {when}
      </Row>
    );
  }
  if (e.kind === 'unstacked') {
    const from = pr(num(d.pr));
    return (
      <Row icon={<GitBranchIcon />}>
        {from ? tx('Unstacked from {pull}', { pull: from }) : t('Unstacked')}
        {str(d.why) && <>: {str(d.why)}</>}
        {when}
      </Row>
    );
  }
  if (e.kind === 'ordered') {
    return (
      <Row icon={<GitBranchIcon />}>
        {tx('Lands after {before} so {after} can build on both', {
          before: pr(num(d.before)),
          after: pr(num(d.for_pr)),
        })}
        {when}
      </Row>
    );
  }
  if (e.kind === 'must_account_for') {
    const first = str(d.rebase_first);
    const instructions = str(d.instructions);
    return (
      <Row icon={<AlertIcon className="pr-warn" />}>
        {tx('Must account for {pull}', { pull: pr(num(d.pr)) })}
        {str(d.reason) && <>: {str(d.reason)}</>}
        {when}
        {first && (
          <div>
            {tx('Rebase onto {branch} first.', {
              branch: <code>{first}</code>,
            })}
          </div>
        )}
        {instructions && (
          <div className="pr-event-more">
            {instructions}
            <div className="muted small">
              {t('Generated by GitOrange; advisory.')}
            </div>
          </div>
        )}
      </Row>
    );
  }
  if (e.kind === 'accounted_for') {
    return (
      <Row icon={<CheckIcon className="pr-ok" />}>
        {tx('Accounted for {pull}', { pull: pr(num(d.pr)) })}
        {str(d.reason) && <>: {str(d.reason)}</>}
        {when}
      </Row>
    );
  }
  if (e.kind === 'dismissed') {
    return (
      <Row icon={<XIcon />}>
        {tx('{who} dismissed the dependency on {pull}', {
          who: e.actor ? (
            <strong>{e.actor.username}</strong>
          ) : (
            t('A maintainer')
          ),
          pull: pr(num(d.pr)),
        })}
        {when}
      </Row>
    );
  }
  if (e.kind === 'approved') {
    const over = Array.isArray(d.over)
      ? (d.over as PullReason[]).filter((r) => r && typeof r.kind === 'string')
      : [];
    const who = e.actor ? (
      <strong>{e.actor.username}</strong>
    ) : (
      t('A former user')
    );
    const via = str(d.via);
    const commit = <code>{(str(d.head_sha) ?? '').slice(0, 7)}</code>;
    const reasons = over.length > 0 ? over.map(reasonText).join('; ') : null;
    const approved = via
      ? reasons
        ? tx('{who} via {via} approved {commit} over {reasons}', {
            who,
            via,
            commit,
            reasons,
          })
        : tx('{who} via {via} approved {commit}', { who, via, commit })
      : reasons
        ? tx('{who} approved {commit} over {reasons}', { who, commit, reasons })
        : tx('{who} approved {commit}', { who, commit });
    return (
      <Row icon={<ShieldCheckIcon className="pr-ok" />}>
        {approved}
        {when}
      </Row>
    );
  }
  if (e.kind === 'withdrawn') {
    return (
      <Row icon={<XIcon />}>
        {tx('{who} withdrew their approval of {commit}', {
          who: e.actor ? (
            <strong>{e.actor.username}</strong>
          ) : (
            t('A former user')
          ),
          commit: <code>{(str(d.head_sha) ?? '').slice(0, 7)}</code>,
        })}
        {when}
      </Row>
    );
  }
  if (e.kind === 'learned') {
    const sha = str(d.sha) ?? '';
    const handle = str(d.handle) ?? 'agent';
    const repository = str(d.repository);
    const findings = num(d.findings) ?? 0;
    const short = <code>{sha.slice(0, 7)}</code>;
    return (
      <Row icon={<LightBulbIcon />}>
        <span title={learnedText(handle, findings, sha)}>
          <strong>@{handle}</strong> {learnedPhrase(findings)} ·{' '}
          {repository && sha ? (
            <Link to={`/${repository}/commit/${sha}`}>{short}</Link>
          ) : (
            short
          )}
        </span>
        {when}
      </Row>
    );
  }
  if (e.kind === 'version_bump') {
    const from = str(d.from);
    const to = str(d.to);
    return (
      <Row icon={<TagIcon />}>
        {!to
          ? tx('{who} cleared the version bump (it counts as patch)', {
              who: e.actor ? (
                <strong>{e.actor.username}</strong>
              ) : (
                t('A former user')
              ),
            })
          : from
            ? tx('{who} changed the version bump from {from} to {to}', {
                who: e.actor ? (
                  <strong>{e.actor.username}</strong>
                ) : (
                  t('A former user')
                ),
                from: <strong>{from}</strong>,
                to: <strong>{to}</strong>,
              })
            : tx('{who} set the version bump to {to}', {
                who: e.actor ? (
                  <strong>{e.actor.username}</strong>
                ) : (
                  t('A former user')
                ),
                to: <strong>{to}</strong>,
              })}
        {when}
      </Row>
    );
  }
  if (e.kind === 'rebased') {
    const to = str(d.to);
    return (
      <Row icon={<GitBranchIcon />}>
        {rebasedText(d)}
        {to && (
          <>
            {' '}
            · <Link to={`${repoPath}/commit/${to}`}>{to.slice(0, 7)}</Link>
          </>
        )}
        {when}
      </Row>
    );
  }
  return null;
}
